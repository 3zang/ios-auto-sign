// Package source fetches AltStore-format subscription sources, detects real
// content changes and upserts app/version metadata into the store.
package source

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"strings"
	"time"

	"ios-auto-sign/internal/store"
)

type altSource struct {
	Apps []altApp `json:"apps"`
}

type altApp struct {
	Name                 string       `json:"name"`
	BundleIdentifier     string       `json:"bundleIdentifier"`
	DeveloperName        string       `json:"developerName"`
	Subtitle             string       `json:"subtitle"`
	LocalizedDescription string       `json:"localizedDescription"`
	IconURL              string       `json:"iconURL"`
	TintColor            string       `json:"tintColor"`
	Versions             []altVersion `json:"versions"`
}

type altVersion struct {
	Version              string `json:"version"`
	Date                 string `json:"date"`
	LocalizedDescription string `json:"localizedDescription"`
	DownloadURL          string `json:"downloadURL"`
	Size                 int64  `json:"size"`
	MinOSVersion         string `json:"minOSVersion"`
	BuildVersion         string `json:"buildVersion"`
}

// AppUpdate describes one newly discovered app version. It is used both in
// the sync API response and as the payload for update notifications.
type AppUpdate struct {
	AppName    string `json:"app_name"`
	BundleID   string `json:"bundle_id"`
	AppID      string `json:"app_id,omitempty"`
	IconURL    string `json:"icon_url,omitempty"`
	Version    string `json:"version"`
	SourceName string `json:"source_name"`
}

// UpdateHook is invoked once per newly discovered version after a successful
// sync. It must be non-blocking from the caller's point of view and should
// never fail the sync itself.
type UpdateHook func(ctx context.Context, u AppUpdate)

type Service struct {
	st     *store.Store
	client *http.Client
	hook   UpdateHook
}

func New(st *store.Store, client *http.Client) *Service {
	return &Service{st: st, client: client}
}

// SetUpdateHook registers the notification callback. It is called once during
// startup, before any sync begins.
func (s *Service) SetUpdateHook(h UpdateHook) { s.hook = h }

type SyncResult struct {
	SourceID     string      `json:"source_id"`
	Changed      bool        `json:"changed"`
	Apps         int         `json:"apps"`
	Versions     int         `json:"versions"`
	NewVersions  int         `json:"new_versions"`
	HTTPStatus   int         `json:"http_status"`
	SkippedByTag bool        `json:"skipped_by_etag"`
	Updates      []AppUpdate `json:"updates,omitempty"`
}

// Sync refreshes one source. A 304 or an unchanged SHA-256 body counts as no
// change, which matters because the upstream source is regenerated by CI every
// six hours even when no app released a new version.
func (s *Service) Sync(ctx context.Context, sourceID string) (*SyncResult, error) {
	src, ok := s.st.Source(sourceID)
	if !ok {
		return nil, fmt.Errorf("source %s not found", sourceID)
	}
	res := &SyncResult{SourceID: sourceID}

	req, err := http.NewRequestWithContext(ctx, http.MethodGet, src.URL, nil)
	if err != nil {
		return nil, err
	}
	if src.ETag != "" {
		req.Header.Set("If-None-Match", src.ETag)
	}
	req.Header.Set("Accept", "application/json")
	resp, err := s.client.Do(req)
	if err != nil {
		s.setError(sourceID, err.Error())
		return nil, err
	}
	defer resp.Body.Close()
	res.HTTPStatus = resp.StatusCode
	if resp.StatusCode == http.StatusNotModified {
		res.SkippedByTag = true
		_ = s.st.Update(func(d *store.Data) error {
			if v := d.Sources[sourceID]; v != nil {
				v.LastCheckedAt = time.Now()
				v.LastError = ""
			}
			return nil
		})
		return res, nil
	}
	if resp.StatusCode != http.StatusOK {
		err := fmt.Errorf("source returned HTTP %d", resp.StatusCode)
		s.setError(sourceID, err.Error())
		return nil, err
	}
	body, err := io.ReadAll(io.LimitReader(resp.Body, 32<<20))
	if err != nil {
		return nil, err
	}
	sum := sha256.Sum256(body)
	hash := hex.EncodeToString(sum[:])

	var parsed altSource
	if err := json.Unmarshal(body, &parsed); err != nil {
		s.setError(sourceID, "invalid JSON: "+err.Error())
		return nil, fmt.Errorf("parse source %s: %w", sourceID, err)
	}
	if hash == src.LastHash {
		_ = s.st.Update(func(d *store.Data) error {
			if v := d.Sources[sourceID]; v != nil {
				v.LastCheckedAt = time.Now()
				v.ETag = resp.Header.Get("ETag")
				v.LastError = ""
			}
			return nil
		})
		return res, nil
	}

	newVersions := 0
	// A brand-new source imports its whole catalogue at once. Those are not
	// "updates", so notifications stay silent on the first successful sync to
	// avoid flooding the device with the entire app list.
	firstSync := src.LastHash == "" && src.LastChangedAt.IsZero()
	err = s.st.Update(func(d *store.Data) error {
		now := time.Now()
		for _, a := range parsed.Apps {
			if strings.TrimSpace(a.BundleIdentifier) == "" {
				continue
			}
			var app *store.App
			for _, existing := range d.Apps {
				if existing.SourceID == sourceID && existing.BundleID == a.BundleIdentifier {
					app = existing
					break
				}
			}
			if app == nil {
				app = &store.App{ID: store.NewID(), SourceID: sourceID, BundleID: a.BundleIdentifier}
				d.Apps[app.ID] = app
			}
			app.Name = a.Name
			app.DeveloperName = a.DeveloperName
			app.Subtitle = a.Subtitle
			app.Description = a.LocalizedDescription
			app.IconURL = a.IconURL
			app.TintColor = a.TintColor
			app.UpdatedAt = now
			res.Apps++
			for _, v := range a.Versions {
				if v.DownloadURL == "" {
					continue
				}
				var found bool
				for _, existing := range d.Versions {
					if existing.AppID == app.ID && existing.Version == v.Version && existing.DownloadURL == v.DownloadURL {
						found = true
						break
					}
				}
				if found {
					res.Versions++
					continue
				}
				ver := &store.AppVersion{
					ID: store.NewID(), AppID: app.ID, Version: v.Version,
					BuildVersion: v.BuildVersion, Date: v.Date,
					DownloadURL: v.DownloadURL, LocalizedDescription: v.LocalizedDescription,
					Size: v.Size, MinOSVersion: v.MinOSVersion, DetectedAt: now,
				}
				d.Versions[ver.ID] = ver
				res.Versions++
				newVersions++
				if !firstSync {
					name := a.Name
					if strings.TrimSpace(name) == "" {
						name = a.BundleIdentifier
					}
					res.Updates = append(res.Updates, AppUpdate{
						AppName: name, BundleID: a.BundleIdentifier,
						AppID: app.ID, IconURL: a.IconURL,
						Version: v.Version, SourceName: src.Name,
					})
				}
			}
		}
		if v := d.Sources[sourceID]; v != nil {
			v.ETag = resp.Header.Get("ETag")
			v.LastHash = hash
			v.LastCheckedAt = now
			v.LastChangedAt = now
			v.LastError = ""
		}
		return nil
	})
	if err != nil {
		res.Updates = nil
		return nil, err
	}
	res.NewVersions = newVersions
	res.Changed = true
	if s.hook != nil {
		for _, up := range res.Updates {
			hctx, cancel := context.WithTimeout(ctx, 15*time.Second)
			s.hook(hctx, up)
			cancel()
		}
	}
	return res, nil
}

func (s *Service) setError(sourceID, msg string) {
	_ = s.st.Update(func(d *store.Data) error {
		if v := d.Sources[sourceID]; v != nil {
			v.LastError = msg
			v.LastCheckedAt = time.Now()
		}
		return nil
	})
}

func (s *Service) SyncAll(ctx context.Context) ([]SyncResult, []error) {
	var ids []string
	s.st.View(func(d *store.Data) {
		for id, src := range d.Sources {
			if src.Enabled {
				ids = append(ids, id)
			}
		}
	})
	var results []SyncResult
	var errs []error
	for _, id := range ids {
		r, err := s.Sync(ctx, id)
		if err != nil {
			errs = append(errs, fmt.Errorf("source %s: %w", id, err))
			continue
		}
		results = append(results, *r)
	}
	return results, errs
}

// ValidateURL rejects non-http schemes and malformed URLs before persisting.
func ValidateURL(raw string) error {
	u, err := url.Parse(strings.TrimSpace(raw))
	if err != nil || u.Host == "" || (u.Scheme != "http" && u.Scheme != "https") {
		return fmt.Errorf("source URL must be an absolute http(s) URL")
	}
	return nil
}
